"""Generate shared frontend DTOs from the core's serialized Pydantic models."""
from __future__ import annotations

import argparse
import asyncio
import contextlib
import difflib
import json
import os
import tempfile
from pathlib import Path

from pydantic import TypeAdapter

from badshop.session.models import ArtifactMeta, Message, Step
from badshop.server.protocol import DocumentContext, Welcome, PROTOCOL_VERSION, GLOBAL_EVENTS
from badshop.server.contracts import EVENTS, ResponseSchema

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'app/src/wire.generated.ts'
NAMES = {'ArtifactMeta': 'Artifact'}


def ts_type(schema: dict) -> str:
    if '$ref' in schema:
        name = schema['$ref'].rsplit('/', 1)[-1]
        return NAMES.get(name, name)
    if 'anyOf' in schema:
        return ' | '.join(ts_type(part) for part in schema['anyOf'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        if 'prefixItems' in schema:
            return '[' + ', '.join(ts_type(item) for item in schema['prefixItems']) + ']'
        return f'Array<{ts_type(schema["items"])}>'
    if kind == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            return '{\n' + ''.join(
                f'  {json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)};\n'
                for name, value in schema['properties'].items()) + '}'
        additional = schema.get('additionalProperties', {})
        return f'Record<string, {ts_type(additional) if isinstance(additional, dict) else "unknown"}>'
    if kind in ('string', 'number', 'integer', 'boolean', 'null'):
        return 'number' if kind == 'integer' else kind
    if not schema or set(schema) <= {'title', 'default', 'description'}:
        return 'unknown'
    raise ValueError(f'Unsupported wire schema: {schema}')


@contextlib.contextmanager
def isolated_environment():
    """Schema discovery must never claim a user's autosave or load their profiles."""
    with tempfile.TemporaryDirectory(prefix='badshop-schema-') as folder:
        values = {key: str(Path(folder) / leaf) for key, leaf in (
            ('BADSHOP_CONFIG_DIR', 'config'), ('BADSHOP_DATA_DIR', 'data'), ('BADSHOP_OUT', 'out'))}
        previous = {key: os.environ.get(key) for key in values}
        try:
            os.environ.update(values)
            yield
        finally:
            for key, value in previous.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value


async def registered_schemas():
    from badshop.server.app import CoreApp
    from badshop.session.execution import InProcessExecutor
    with isolated_environment():
        app = CoreApp(executor_factory=lambda **_: InProcessExecutor())
        try:
            return app.dispatcher.schemas()
        finally:
            await app.close()


def generate() -> str:
    definitions = {}
    methods = asyncio.run(registered_schemas())
    events = {name: TypeAdapter(model).json_schema(mode='serialization', schema_generator=ResponseSchema)
              for name, model in sorted(EVENTS.items())}

    def response_names(value):
        # Input defaults are optional; serialized defaults are present. Distinct
        # definitions prevent a request schema from weakening a response schema.
        if isinstance(value, dict):
            return {key: ('#/$defs/Response' + item.rsplit('/', 1)[-1] if key == '$ref' else
                          {'Response' + name: response_names(body) for name, body in item.items()}
                          if key == '$defs' else response_names(item)) for key, item in value.items()}
        if isinstance(value, list):
            return [response_names(item) for item in value]
        return value

    for entry in methods.values():
        entry['result'] = response_names(entry['result'])
    events = {name: response_names(schema) for name, schema in events.items()}
    for entry in methods.values():
        for kind in ('params', 'result'):
            definitions.update(entry[kind].pop('$defs', {}))
    for schema in events.values():
        definitions.update(schema.pop('$defs', {}))
    for model in (ArtifactMeta, Step, Message, DocumentContext, Welcome):
        schema = model.model_json_schema(mode='serialization')
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    header = ('// Generated by scripts/generate_wire_types.py; do not edit.\n'
              '// Defaults may be omitted in UI fixtures; nullable wire fields retain null.\n')
    constants = (f'export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n'
                 f'export const GLOBAL_EVENTS: readonly string[] = {json.dumps(sorted(GLOBAL_EVENTS))};\n')
    types = '\n'.join(
        f'export type {NAMES.get(name, name)} = {ts_type(schema)};\n'
        for name, schema in sorted(definitions.items()))
    method_types = 'export interface WireMethodMap {\n' + ''.join(
        f'  {json.dumps(name)}: [{ts_type(entry["params"])}'
        f'{" | undefined" if not entry["params"].get("required") else ""}, {ts_type(entry["result"])}];\n'
        for name, entry in methods.items()) + '}\n'
    event_types = 'export type WireEvent =\n' + '\n'.join(
        f'  | {{ method: {json.dumps(name)}; params: {ts_type(schema)} }}'
        for name, schema in events.items()) + ';\n'
    runtime = '\nexport const WIRE_SCHEMAS = ' + json.dumps(
        {'definitions': definitions, 'methods': methods, 'events': events},
        ensure_ascii=True, separators=(',', ':')) + ';\n'
    return header + constants + types + method_types + event_types + runtime


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    actual = DESTINATION.read_text(encoding='utf-8') if DESTINATION.exists() else ''
    if args.check:
        if actual != expected:
            print('Shared wire types are stale; run scripts/generate_wire_types.py')
            print(''.join(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True),
                                             fromfile=str(DESTINATION), tofile='core schemas')))
            return 1
        print('Shared wire types match core serialization schemas.')
    else:
        DESTINATION.write_text(expected, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
