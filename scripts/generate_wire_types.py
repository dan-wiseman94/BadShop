"""Generate shared frontend DTOs from the core's serialized Pydantic models."""
from __future__ import annotations

import argparse
import difflib
import json
from pathlib import Path

from badshop.session.models import ArtifactMeta, Message, Step

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'app/src/wire.generated.ts'
NAMES = {'ArtifactMeta': 'Artifact'}


def ts_type(schema: dict) -> str:
    if '$ref' in schema:
        name = schema['$ref'].rsplit('/', 1)[-1]
        return NAMES.get(name, name)
    if 'anyOf' in schema:
        return ' | '.join(ts_type(part) for part in schema['anyOf'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        return f'Array<{ts_type(schema["items"])}>'
    if kind == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            return '{\n' + ''.join(
                f'  {name}{"" if name in required else "?"}: {ts_type(value)};\n'
                for name, value in schema['properties'].items()) + '}'
        additional = schema.get('additionalProperties', {})
        return f'Record<string, {ts_type(additional) if isinstance(additional, dict) else "unknown"}>'
    if kind in ('string', 'number', 'integer', 'boolean', 'null'):
        return 'number' if kind == 'integer' else kind
    if not schema:
        return 'unknown'
    raise ValueError(f'Unsupported wire schema: {schema}')


def generate() -> str:
    definitions = {}
    for model in (ArtifactMeta, Step, Message):
        schema = model.model_json_schema(mode='serialization')
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    header = ('// Generated by scripts/generate_wire_types.py; do not edit.\n'
              '// Defaults may be omitted in UI fixtures; nullable wire fields retain null.\n')
    return header + '\n'.join(
        f'export type {NAMES.get(name, name)} = {ts_type(schema)};\n'
        for name, schema in sorted(definitions.items()))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    actual = DESTINATION.read_text(encoding='utf-8') if DESTINATION.exists() else ''
    if args.check:
        if actual != expected:
            print('Shared wire types are stale; run scripts/generate_wire_types.py')
            print(''.join(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True),
                                             fromfile=str(DESTINATION), tofile='core schemas')))
            return 1
        print('Shared wire types match core serialization schemas.')
    else:
        DESTINATION.write_text(expected, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
