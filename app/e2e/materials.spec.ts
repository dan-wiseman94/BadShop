test("real layouts, installed asset packs, and image pair composition stay editable", async ({ page, core }) => {
  await setup(page, core);
  await page.getByRole("button", { name: "Layouts & packs", exact: true }).click();
  const initial = await core.call("session.get") as Session;
  const source = Object.keys(initial.artifacts)[0];
  await page.getByLabel("Layout title").fill("EMPLOYEE OF THE MONTH");
  await page.getByLabel("Image for Character", { exact: true }).selectOption(source);
  await page.getByRole("combobox", { name: /Image fitting/ }).selectOption("cover");
  await page.getByLabel("Horizontal crop focus for Character", { exact: true }).fill("0.1");
  await page.getByLabel("Caption for Character", { exact: true }).fill("Exceeds all expectations");
  await page.getByLabel("Panel border (px)", { exact: true }).fill("6");
  await page.getByLabel("Panel inner margin (px)", { exact: true }).fill("12");
  await page.getByRole("button", { name: "Preview layout", exact: true }).click();
  const preview = page.getByAltText("Uncommitted layout preview");
  await expect(preview).toBeVisible();
  const previewBytes = (await preview.getAttribute("src"))!.split(",")[1];
  expect((await core.call("session.get") as Session).steps).toEqual(initial.steps);
  await page.getByRole("button", { name: "Create layout", exact: true }).click();
  await expect(page.getByText("Layout created and attached to chat.")).toBeVisible();
  const built = await core.call("session.get") as Session;
  expect(built.steps.at(-1)?.tool).toBe("layout");
  expect(built.steps.at(-1)?.params.focal_points).toEqual([[0.1, 0.5]]);
  const card = built.steps.at(-1)!.outputs[0];
  expect(built.steps.at(-1)?.params).toMatchObject({ panel_border: 6, panel_padding: 12, exact_text: true });
  expect((await core.call("artifacts.get", { id: card }) as { data: string }).data).toBe(previewBytes);
  const packButtons = page.getByRole("button", { name: /^Install / });
  await expect(packButtons).toHaveCount(12);
  await packButtons.first().click();
  await expect(page.getByText(/assets added to your junk drawer/)).toBeVisible();
  const entries = await core.call("library.list") as LibraryEntry[];
  expect(entries.length).toBeGreaterThanOrEqual(4);
  const pack = path.join(core.folder, "favorite.badpack");
  await core.call("packs.export", { ids: [entries[0].id], path: pack });
  await core.call("packs.import", { path: pack });
  await page.getByRole("button", { name: "Image pairs", exact: true }).click();
  await page.getByLabel("Donor images (up to six)").selectOption([source]);
  await page.getByLabel("Background images (up to six)").selectOption([card]);
  await page.getByRole("button", { name: "Compare image pairs" }).click();
  await expect(page.getByRole("button", { name: "Compose this pair" })).toBeVisible();
  await page.getByRole("button", { name: "Compose this pair" }).click();
  await expect(page.getByRole("status")).toContainText("editable paste step");
  expect((await core.call("session.get") as Session).steps.at(-1)?.tool).toBe("paste");
  await page.screenshot({ path: test.info().outputPath("badshop-material-pairs.png") });
});

test("bundled PDF preview imports the selected page region and persists its bytes", async ({ page, core }) => {
  const source = path.join(core.folder, "pages.pdf");
  execFileSync(python, ["-c", "from PIL import Image; import sys; Image.new('RGB',(80,60),'red').save(sys.argv[1],format='PDF',save_all=True,append_images=[Image.new('RGB',(80,60),'blue')])", source]);
  await setup(page, core);
  await page.getByRole("button", { name: "Clips, pages & folders" }).click();
  await page.getByRole("button", { name: "Pages / scans" }).click();
  await page.getByLabel("Selected source file").fill(source);
  await page.getByLabel("Page number", { exact: true }).fill("2");
  await page.getByRole("button", { name: "Preview source", exact: true }).click();
  await page.getByRole("checkbox", { name: "Select Page 2", exact: true }).check();
  await page.getByLabel("Crop right").fill("40");
  await page.getByLabel("Crop bottom").fill("30");
  await page.getByRole("button", { name: "Import selected region" }).click();
  await expect.poll(async () => {
    const step = (await core.call("session.get") as Session).steps.at(-1);
    return step?.tool === "cutout" && step.status === "done" && !!step.outputs[0];
  }).toBe(true);
  const session = await core.call("session.get") as Session;
  const output = session.steps.at(-1)!.outputs[0];
  expect(session.artifacts[output].width).toBe(40);
  expect(session.artifacts[output].height).toBe(30);
  const payload = await core.call("artifacts.get", { id: output }) as { data: string };
  const pixel = execFileSync(python, ["-c", "from PIL import Image; import io,base64,sys,json; print(json.dumps(Image.open(io.BytesIO(base64.b64decode(sys.argv[1]))).getpixel((20,15))))", payload.data], { encoding: "utf8" });
  const [red, green, blue] = JSON.parse(pixel) as number[];
  expect(red).toBeLessThan(10); expect(green).toBeLessThan(10); expect(blue).toBeGreaterThan(240);
  const file = path.join(core.folder, "page.badshop");
  await core.call("session.save_as", { path: file });
  await core.call("session.open", { path: file });
  expect((await core.call("artifacts.get", { id: output }) as { data: string }).data).toBe(payload.data);
});

test("one file input routes pictures and clips and cancelling pending pages retains imports", async ({ page, emptyCore }) => {
  const video = path.join(emptyCore.folder, "clip.mp4");
  const pdf = path.join(emptyCore.folder, "page.pdf");
  execFileSync(python, ["-c", "import av,sys\nfrom PIL import Image\nwith av.open(sys.argv[1],'w') as out:\n s=out.add_stream('mpeg4',rate=3)\n s.width,s.height,s.pix_fmt=80,60,'yuv420p'\n for color in ('red','green','blue'):\n  for p in s.encode(av.VideoFrame.from_image(Image.new('RGB',(80,60),color))): out.mux(p)\n for p in s.encode(): out.mux(p)\nImage.new('RGB',(80,60),'blue').save(sys.argv[2],format='PDF')", video, pdf]);
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Edit a photo without AI" }).click();
  await page.getByRole("region", { name: "Image viewer" }).getByRole("button", { name: "Add images", exact: true }).click();
  const sources = page.getByRole("dialog", { name: "Add material", exact: true });
  await expect(sources.getByLabel("Image link", { exact: true })).toBeVisible();
  const choosing = page.waitForEvent("filechooser");
  await sources.getByRole("button", { name: "Choose files", exact: true }).click();
  await (await choosing).setFiles([path.join(root, "core/tests/fixtures/lincoln.png"), video, pdf]);
  const dialog = page.getByRole("dialog", { name: "Import media", exact: true });
  await expect(dialog.getByText("2 file(s) waiting.", { exact: false })).toBeVisible();
  await expect(dialog.getByLabel("Selected source file")).toHaveValue("clip.mp4");
  await dialog.getByRole("button", { name: "Preview source", exact: true }).click();
  await dialog.getByRole("checkbox", { name: "Select At 0.000s", exact: true }).check();
  await dialog.getByRole("button", { name: "Import selected frames", exact: true }).click();
  await expect(dialog.getByText(/image\(s\) added to chat/)).toBeVisible();
  const before = await emptyCore.call("session.get") as Session;
  const imported = Object.values(before.artifacts).find(item => item.source?.kind === "local-media")!;
  expect(imported.width).toBe(80);
  const bytes = (await emptyCore.call("artifacts.get", { id: imported.id }) as { data: string }).data;
  const pixel = JSON.parse(execFileSync(python, ["-c", "from PIL import Image; import base64,io,sys,json; print(json.dumps(Image.open(io.BytesIO(base64.b64decode(sys.argv[1]))).getpixel((10,10))))", bytes], { encoding: "utf8" })) as number[];
  expect(pixel[0]).toBeGreaterThan(240); expect(pixel[1]).toBeLessThan(10); expect(pixel[2]).toBeLessThan(10);
  await dialog.getByRole("button", { name: "Done / next file", exact: true }).click();
  await expect(dialog.getByLabel("Selected source file")).toHaveValue("page.pdf");
  await dialog.getByRole("button", { name: "Cancel remaining imports", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect((await emptyCore.call("session.get") as Session).artifacts).toEqual(before.artifacts);
  const file = path.join(emptyCore.folder, "mixed.badshop");
  await emptyCore.call("session.save_as", { path: file });
  await emptyCore.call("session.open", { path: file });
  expect((await emptyCore.call("artifacts.get", { id: imported.id }) as { data: string }).data).toBe(bytes);
});

test("private screen capture can be cancelled or cropped and annotated before reopening", async ({ page, emptyCore }) => {
  test.skip(process.env.BADSHOP_PRIVATE_CAPTURE_TEST !== "1", "Requires private Xvfb; never capture the user's desktop");
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Edit a photo without AI" }).click();
  const viewer = page.getByRole("region", { name: "Image viewer" });
  const capture = async () => {
    await viewer.getByRole("button", { name: "Add images", exact: true }).click();
    await page.getByRole("dialog", { name: "Add material", exact: true }).getByRole("button", { name: "Capture screen region", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Import media", exact: true })).toBeVisible();
  };
  await capture();
  const dialog = page.getByRole("dialog", { name: "Import media", exact: true });
  expect(Object.keys((await emptyCore.call("session.get") as Session).artifacts)).toHaveLength(0);
  await dialog.getByRole("button", { name: "Cancel remaining imports", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(Object.keys((await emptyCore.call("session.get") as Session).artifacts)).toHaveLength(0);
  await capture();
  await dialog.getByLabel("Crop right").fill("100");
  await dialog.getByLabel("Crop bottom").fill("80");
  await dialog.getByRole("button", { name: "Import selected region", exact: true }).click();
  await expect(dialog.getByText(/image\(s\) added to chat/)).toBeVisible();
  await dialog.getByRole("button", { name: "Done / next file", exact: true }).click();
  const before = await emptyCore.call("session.get") as Session;
  const cropped = Object.values(before.artifacts).find(image => image.source?.kind === "screen-capture")!.id;
  expect(Object.keys(before.artifacts)).toHaveLength(1);
  expect(before.artifacts[cropped].original_id).toBeNull();
  expect([before.artifacts[cropped].width, before.artifacts[cropped].height]).toEqual([100, 80]);
  const manual = viewer.locator("details.manual-tools");
  await manual.locator("summary").click();
  await manual.getByRole("button", { name: "Text", exact: true }).click();
  await manual.getByRole("textbox", { name: /^Text/ }).fill("Look here");
  await manual.getByRole("button", { name: "Apply text", exact: true }).click();
  await expect.poll(async () => {
    const step = (await emptyCore.call("session.get") as Session).steps.at(-1);
    return step?.tool === "text" && step.status === "done" && !!step.outputs[0];
  }).toBe(true);
  const after = await emptyCore.call("session.get") as Session;
  const output = after.steps.at(-1)!.outputs[0];
  expect(output).not.toBe(cropped);
  const bytes = (await emptyCore.call("artifacts.get", { id: output }) as { data: string }).data;
  const file = path.join(emptyCore.folder, "capture.badshop");
  await emptyCore.call("session.save_as", { path: file });
  await emptyCore.call("session.open", { path: file });
  expect((await emptyCore.call("artifacts.get", { id: output }) as { data: string }).data).toBe(bytes);
});

