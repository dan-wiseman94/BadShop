test("GIF frame editing previews without mutation and persists exact animation bytes", async ({ page, emptyCore }) => {
  const source = path.join(emptyCore.folder, "frames.gif");
  execFileSync(python, ["-c", "from PIL import Image; import sys; Image.new('RGB',(80,60),'red').save(sys.argv[1],save_all=True,append_images=[Image.new('RGB',(80,60),'green'),Image.new('RGB',(80,60),'blue')],duration=[80,170,240],loop=3)", source]);
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Edit a photo without AI" }).click();
  await page.getByLabel("Import image files").setInputFiles(source);
  await expect(page.locator(".canvas-image")).toBeVisible();
  const manual = page.locator("details.manual-tools");
  await manual.locator("summary").click();
  await manual.getByRole("button", { name: "Edit GIF frames", exact: true }).click();
  const before = await emptyCore.call("session.get") as Session;
  const original = Object.values(before.artifacts).find(item => item.frames === 3)!;
  const originalBytes = await emptyCore.call("artifacts.get", { id: original.id });
  await manual.getByRole("button", { name: "Reverse frames", exact: true }).click();
  await manual.getByRole("button", { name: "Preview changes", exact: true }).click();
  const preview = manual.getByAltText("Uncommitted preview 1");
  await expect(preview).toBeVisible();
  await expect(preview).toHaveAttribute("src", /^data:image\/gif;base64,/);
  expect((await emptyCore.call("session.get") as Session).steps).toEqual(before.steps);
  await manual.getByRole("button", { name: "Cancel changes", exact: true }).click();
  await expect(preview).toHaveCount(0);
  await manual.getByRole("button", { name: "Reverse frames", exact: true }).click();
  await manual.getByRole("button", { name: "Duplicate frame", exact: true }).click();
  await manual.getByRole("button", { name: "Move frame later", exact: true }).click();
  await manual.getByRole("button", { name: "Delete frame", exact: true }).click();
  await manual.getByRole("button", { name: "Hold frame for 1 second", exact: true }).click();
  await manual.getByRole("button", { name: "Ping-pong frames", exact: true }).click();
  await manual.getByLabel("Trim first output frame").fill("2");
  await manual.getByLabel("Trim last output frame").fill("4");
  await manual.getByRole("button", { name: "Trim to range", exact: true }).click();
  await manual.getByLabel("Speed", { exact: true }).fill("2");
  await manual.getByLabel("Crop X1", { exact: true }).fill("10");
  await manual.getByLabel("Crop Y1", { exact: true }).fill("10");
  await manual.getByLabel("Crop X2", { exact: true }).fill("70");
  await manual.getByLabel("Crop Y2", { exact: true }).fill("50");
  await manual.getByRole("button", { name: "Add item", exact: true }).click();
  await manual.getByRole("textbox", { name: /^Text/ }).fill("Hi");
  await manual.getByLabel(/^End/).fill("2");
  await manual.getByRole("button", { name: "Preview changes", exact: true }).click();
  await expect(preview).toBeVisible();
  const expected = (await preview.getAttribute("src"))!.split(",")[1];
  const decoded = JSON.parse(execFileSync(python, ["-c", "from PIL import Image,ImageSequence; import io,base64,json,sys; im=Image.open(io.BytesIO(base64.b64decode(sys.argv[1]))); print(json.dumps({'size':im.size,'durations':[f.info['duration'] for f in ImageSequence.Iterator(im)],'caption':[any(p==(255,255,255) for p in f.convert('RGB').get_flattened_data()) for f in ImageSequence.Iterator(im)]}))", expected], { encoding: "utf8" }));
  expect(decoded).toEqual({ size: [60, 40], durations: [500, 40, 500], caption: [true, true, false] });
  expect((await emptyCore.call("session.get") as Session).artifacts).toEqual(before.artifacts);
  await manual.getByRole("button", { name: "Apply edit gif frames", exact: true }).click();
  expect(await manual.locator("input:invalid, select:invalid").evaluateAll(inputs => inputs.map(input => ({
    label: input.getAttribute("aria-label") ?? input.getAttribute("label"),
    value: (input as HTMLInputElement).value, error: (input as HTMLInputElement).validationMessage,
  })))).toEqual([]);
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  const edited = (await emptyCore.call("session.get") as Session).steps[0];
  expect(edited.data).toMatchObject({ source_frames: [1, 0, 1], durations: [500, 40, 500], loop: 3 });
  expect((await emptyCore.call("artifacts.get", { id: edited.outputs[0] }) as { data: string }).data).toBe(expected);
  expect(await emptyCore.call("artifacts.get", { id: original.id })).toEqual(originalBytes);
  const file = path.join(emptyCore.folder, "animation.badshop");
  await emptyCore.call("session.save_as", { path: file });
  await emptyCore.call("session.open", { path: file });
  await emptyCore.call("history.undo", { expected_revision: (await emptyCore.call("session.get") as Session).document_revision });
  expect((await emptyCore.call("session.get") as Session).steps).toHaveLength(0);
  await emptyCore.call("history.redo", { expected_revision: (await emptyCore.call("session.get") as Session).document_revision });
  expect((await emptyCore.call("session.get") as Session).steps[0].outputs).toEqual(edited.outputs);
  await emptyCore.call("steps.edit", { step_id: edited.id, params: edited.params });
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0].status).toBe("done");
  expect((await emptyCore.call("session.get") as Session).steps[0].outputs).toEqual(edited.outputs);
});

test("custom export prepares and saves exact dimensions within a readable size budget", async ({ page, emptyCore }) => {
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByRole("button", { name: /An error with no solution/ }).click();
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await expect(page.locator(".canvas-image")).toBeVisible();
  const before = await emptyCore.call("session.get") as Session;
  await page.getByRole("button", { name: "Export", exact: true }).click();
  await page.getByText("Resize or change format", { exact: true }).click();
  await page.getByLabel("Output width (optional)").fill("240");
  await page.getByRole("button", { name: "Prepare and save" }).click();
  await expect(page.getByRole("alert")).toContainText("both width and height");
  expect((await emptyCore.call("session.get") as Session).steps).toHaveLength(before.steps.length);
  await page.getByLabel("Output height (optional)").fill("160");
  await page.getByLabel("Maximum file size (optional)").fill("50");
  await page.getByLabel("Export preset name").fill("Chat attachment");
  await page.getByRole("button", { name: "Save export settings", exact: true }).click();
  await expect(page.getByRole("button", { name: "Use Chat attachment", exact: true })).toBeVisible();
  await page.getByLabel("Output width (optional)").fill("120");
  await page.getByLabel("Output height (optional)").fill("80");
  await page.getByLabel("Export preset name").fill("Small attachment");
  await page.getByRole("button", { name: "Save export settings", exact: true }).click();
  await expect(page.getByRole("button", { name: "Use Small attachment", exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Export", exact: true }).click();
  await page.getByText("Resize or change format", { exact: true }).click();
  await page.getByRole("button", { name: "Use Chat attachment", exact: true }).click();
  await expect(page.getByLabel("Output width (optional)")).toHaveValue("240");
  await expect(page.getByLabel("Output height (optional)")).toHaveValue("160");
  await expect(page.getByLabel("Maximum file size (optional)")).toHaveValue("50");
  await page.getByLabel("Include Chat attachment", { exact: true }).check();
  await page.getByLabel("Include Small attachment", { exact: true }).check();
  await page.getByRole("button", { name: "Prepare selected sizes", exact: true }).click();
  await expect(page.getByAltText("Chat attachment prepared output")).toBeVisible();
  await expect(page.getByAltText("Small attachment prepared output")).toBeVisible();
  const multiple = await emptyCore.call("session.get") as Session;
  expect(multiple.steps.slice(-2).map(step => {
    const image = multiple.artifacts[step.outputs[0]];
    return [image.width, image.height];
  })).toEqual([[240, 160], [120, 80]]);
  await page.getByRole("button", { name: "Prepare and save" }).click();
  await expect(page.getByRole("status")).toContainText("Exported to ");
  const filename = (await page.getByRole("status").innerText()).replace("Exported to ", "").trim();
  const bytes = await readFile(filename);
  expect(bytes.length).toBeLessThanOrEqual(50000);
  expect(bytes.readUInt32BE(16)).toBe(240);
  expect(bytes.readUInt32BE(20)).toBe(160);
  const after = await emptyCore.call("session.get") as Session;
  expect(after.steps.at(-1)?.params.max_bytes).toBe(50000);
  expect(after.steps.at(-1)?.outputs[0]).toBe(createHash("sha256").update(bytes).digest("hex"));
  expect(after.steps[0].outputs).toEqual(before.steps[0].outputs);
});

