test("a pending replacement picture blocks collection creation until its real import completes", async ({ page, emptyCore }) => {
  let releaseImport: (() => void) | undefined;
  await page.routeWebSocket(`ws://127.0.0.1:${emptyCore.port}/`, client => {
    const server = client.connectToServer();
    client.onMessage(frame => {
      const request = JSON.parse(String(frame));
      if (request.method === "artifacts.import" && request.params.name === "lincoln.png") {
        releaseImport = () => server.send(frame);
      } else server.send(frame);
    });
  });
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByRole("button", { name: /A deeply useless trading card/ }).click();
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  await page.getByText("Make a scene: surprises & reaction sets", { exact: true }).click();
  await page.getByLabel("Import image files").setInputFiles(path.join(root, "core/tests/fixtures/lincoln.png"));
  await expect(page.getByText("Opening your picture…", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Make three alternate takes" })).toBeDisabled();
  await expect.poll(() => !!releaseImport).toBe(true);
  releaseImport!();
  await page.getByRole("button", { name: "Make three alternate takes" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[3]?.status).toBe("done");
  const made = await emptyCore.call("session.get") as Session;
  for (const step of made.steps.slice(1)) expect(made.artifacts[(step.params.images as string[])[0]].label).toContain("lincoln");
});

test("collections preserve explicit words and create real reaction images and a replay GIF", async ({ page, emptyCore }, info) => {
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByLabel("Import image files").setInputFiles(path.join(root, "core/tests/fixtures/lincoln.png"));
  await page.getByRole("button", { name: /A deeply useless trading card/ }).click();
  await page.getByLabel("Headline", { exact: true }).fill("Our exact headline");
  await page.getByLabel("Punchline", { exact: true }).fill("Our exact joke");
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  await page.getByLabel("Revised punchline").fill("");
  await page.getByRole("button", { name: "Change caption only" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.params.captions).toEqual([""]);
  await page.getByText("Make a scene: surprises & reaction sets", { exact: true }).click();
  await page.getByLabel("Keep my current headline and punchline exactly").check();
  await page.getByRole("button", { name: "Make three alternate takes" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[3]?.status).toBe("done");
  const takes = (await emptyCore.call("session.get") as Session).steps.slice(1);
  const made = await emptyCore.call("session.get") as Session;
  expect(made.artifacts[(takes[0].params.images as string[])[0]].label).toContain("lincoln");
  expect(takes.map(s => s.params.title)).toEqual(Array(3).fill("Our exact headline"));
  expect(takes.map(s => s.params.captions)).toEqual(Array(3).fill([""]));
  expect(new Set(takes.map(s => s.outputs[0])).size).toBe(3);
  await page.getByLabel("Keep my current headline and punchline exactly").uncheck();
  await page.getByLabel("Make six reactions for the group chat").check();
  await page.getByRole("button", { name: "Make my reaction set" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[9]?.status).toBe("done");
  const reactions = (await emptyCore.call("session.get") as Session).steps.slice(4);
  expect(new Set(reactions.map(s => s.outputs[0])).size).toBe(6);
  await page.getByText("Show how it happened", { exact: true }).click();
  await page.getByLabel("Replay frame 1", { exact: true }).check();
  await page.getByLabel("Replay frame 2", { exact: true }).check();
  await page.getByRole("button", { name: "Make creation replay GIF" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps.at(-1)?.tool).toBe("animate");
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps.at(-1)?.status).toBe("done");
  const session = await emptyCore.call("session.get") as Session;
  const gif = session.steps.at(-1)!.outputs[0];
  expect(session.artifacts[gif].frames).toBe(2);
  const exported = await emptyCore.call("export", { artifact_id: gif }) as { path: string };
  expect((await readFile(exported.path)).subarray(0, 6).toString()).toMatch(/^GIF8[79]a$/);
  const first = await emptyCore.call("artifacts.frame", { id: gif, frame: 0 });
  const second = await emptyCore.call("artifacts.frame", { id: gif, frame: 1 });
  expect(first).not.toEqual(second);
  await page.screenshot({ path: info.outputPath("collections-and-replay.png") });
});

test("share preview exports an editable remix that opens and changes its joke", async ({ page, emptyCore }, info) => {
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByRole("button", { name: /A deeply useless trading card/ }).click();
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  await page.getByRole("button", { name: "Export image", exact: true }).click();
  const sharing = page.getByRole("dialog", { name: "Export image" });
  await sharing.getByText("Let someone remix this", { exact: true }).click();
  await sharing.getByRole("button", { name: "Save editable remix" }).click();
  const saved = sharing.getByRole("status").filter({ hasText: "Editable remix saved to" });
  await expect(saved).toBeVisible();
  const filename = (await saved.textContent())!.replace("Editable remix saved to ", "");
  expect((await readFile(filename)).subarray(0, 2).toString()).toBe("PK");
  await emptyCore.call("session.new", { discard_unsaved: true });
  await emptyCore.call("session.open", { path: filename });
  await page.reload();
  const before = (await emptyCore.call("session.get") as Session).steps[0].outputs[0];
  await page.getByLabel("Revised punchline").fill("Remixed by a friend");
  await page.getByRole("button", { name: "Change caption only" }).click();
  await expect.poll(async () => {
    const step = (await emptyCore.call("session.get") as Session).steps[0];
    return step.status === "done" && step.outputs[0] !== before;
  }).toBe(true);
  await emptyCore.call("session.save_as", { path: info.outputPath("remixed.badshop") });
});

test("a pass-and-play challenge keeps independent rounds after reopening", async ({ page, emptyCore }, info) => {
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByRole("button", { name: /A deeply useless trading card/ }).click();
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await page.getByLabel("Challenge prompt").fill("First game");
  await page.getByRole("button", { name: "Keep this scene as a challenge start" }).click();
  await expect.poll(async () => (await emptyCore.call("branches.list") as BranchList).branches.length).toBe(2);
  await expect(page.getByLabel("Player or round name")).toBeHidden();
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await page.getByLabel("Challenge prompt").fill("Second game");
  await page.getByRole("button", { name: "Keep this scene as a challenge start" }).click();
  await expect.poll(async () => (await emptyCore.call("branches.list") as BranchList).branches.length).toBe(3);
  await expect(page.getByLabel("Player or round name")).toBeHidden();
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await page.getByLabel("Saved challenge").selectOption({ label: "First game" });
  await page.getByLabel("Player or round name").fill("Ada");
  await page.getByRole("button", { name: "Start this player's round" }).click();
  await expect.poll(async () => (await emptyCore.call("branches.list") as BranchList).branches.length).toBe(4);
  await page.getByLabel("Revised punchline").fill("Ada's version");
  await page.getByRole("button", { name: "Change caption only" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps[0]?.status).toBe("done");
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await expect(page.getByLabel("Saved challenge").locator("option:checked")).toHaveText("First game");
  await page.getByLabel("Player or round name").fill("Grace");
  await page.getByRole("button", { name: "Start this player's round" }).click();
  await expect.poll(async () => (await emptyCore.call("branches.list") as BranchList).branches.length).toBe(5);
  expect((await emptyCore.call("session.get") as Session).steps[0].params.captions).not.toEqual(["Ada's version"]);
  await emptyCore.call("session.save_as", { path: info.outputPath("challenge.badshop") });
  await emptyCore.call("session.new", { discard_unsaved: true });
  await emptyCore.call("session.open", { path: info.outputPath("challenge.badshop") });
  await page.reload();
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await page.getByRole("button", { name: "Reveal the takes" }).click();
  const challenge = page.getByRole("region", { name: "Remix challenge" });
  await expect(challenge.getByText("Ada", { exact: true })).toBeVisible();
  await expect(challenge.getByText("Grace", { exact: true })).toBeVisible();
  await challenge.getByRole("button", { name: "Give this take a star" }).first().click();
  await expect(challenge.getByText("Ada ★", { exact: true })).toBeVisible();
  const voted = await emptyCore.call("branches.list") as BranchList;
  const project = info.outputPath("challenge.badshop");
  await page.getByRole("button", { name: "Save session", exact: true }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).unsaved_changes).toBe(false);
  await page.reload();
  await page.getByText("Play a remix challenge", { exact: true }).click();
  await page.getByRole("button", { name: "Reveal the takes" }).click();
  await expect(challenge.getByText("Ada ★", { exact: true })).toBeVisible();
  await expect(challenge.locator("article").filter({ hasText: "Ada ★" }).getByRole("button", { name: "Give this take a star" })).toBeDisabled();
  await emptyCore.call("session.open", { path: project });
  expect((await emptyCore.call("branches.list") as BranchList).branches).toEqual(voted.branches);
});
