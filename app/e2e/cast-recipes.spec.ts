import path from "node:path";
import { test, expect, root } from "./fixtures";
import type { Session, LibraryEntry, Recipe } from "../src/types";

test("a saved character survives a new project and a visual recipe makes reusable pixels", async ({ page, emptyCore }, info) => {
  await page.goto(`/?core_port=${emptyCore.port}&core_token=${emptyCore.token}`);
  await page.getByRole("button", { name: "Start with a quick idea" }).click();
  await page.getByLabel("Import image files").setInputFiles(path.join(root, "core/tests/fixtures/lincoln.png"));
  await page.getByText("Your cast of characters", { exact: true }).click();
  await page.getByLabel("Character name", { exact: true }).fill("Office Abe");
  await page.getByLabel("Expression or role").fill("Unimpressed");
  await page.getByLabel("Cast collection", { exact: true }).fill("Worst workplace");
  await page.getByRole("button", { name: "Keep this picture in my cast" }).click();
  await expect(page.getByRole("button", { name: "Use Office Abe" })).toBeVisible();
  const cast = await emptyCore.call("library.list") as LibraryEntry[];
  expect(cast[0].tags).toContain("collection:Worst workplace");
  await emptyCore.call("session.new", { discard_unsaved: true });
  await page.reload();
  await page.getByText("Your cast of characters", { exact: true }).click();
  await page.getByRole("button", { name: "Use Office Abe" }).click();
  await expect(page.getByAltText("Preview with your picture")).toHaveCount(6);
  await page.getByRole("button", { name: /Two panels, one bad decision/ }).click();
  await page.getByRole("button", { name: "Make this shitpost" }).click();
  await page.getByText("Save a reusable recipe", { exact: true }).click();
  await page.getByRole("button", { name: "Capture selected step" }).click();
  await page.getByLabel("Recipe name", { exact: true }).fill("Our running joke");
  await page.getByRole("button", { name: "Keep these recipe controls" }).click();
  await page.getByRole("button", { name: "Save recipe", exact: true }).click();
  await expect.poll(async () => ((await emptyCore.call("session.get") as Session).recipes as Recipe[])[0]?.name).toBe("Our running joke");
  const saved = await emptyCore.call("session.get") as Session;
  expect(saved.recipes![0].steps[0].params.images).toEqual(["$input", "$input"]);
  await page.getByRole("group", { name: "Pictures to use (up to 12)" }).getByRole("checkbox").first().check();
  await page.getByRole("button", { name: "Run recipe on selected pictures" }).click();
  await expect.poll(async () => (await emptyCore.call("session.get") as Session).steps.at(1)?.status).toBe("done");
  const after = await emptyCore.call("session.get") as Session;
  expect(after.steps.at(-1)!.outputs).toEqual(saved.steps[0].outputs);
  await emptyCore.call("session.save_as", { path: info.outputPath("cast-recipe.badshop") });
  await emptyCore.call("session.new", { discard_unsaved: true });
  await emptyCore.call("session.open", { path: info.outputPath("cast-recipe.badshop") });
  expect((await emptyCore.call("session.get") as Session).recipes).toEqual(saved.recipes);
});
